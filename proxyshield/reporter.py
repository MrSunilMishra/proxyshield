def generate_json_report(audit_data: Dict[str, Any], filepath: str) -> None:
    """Exports full audit and transparency metrics to JSON."""
    report = {
        "report_title": "ProxyShield Network Security Audit & Transparency Report",
        "author": "Quarkova",
        "organization": "Quarkova",
        "website": "https://quarkova.com",
        "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "legal_notice": LEGAL_PRIVACY_NOTICE,
        "direct_ip_fallback": "DISABLED (STRICT_PROXY_ONLY)",
        **audit_data
    }
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)


def generate_csv_report(audit_data: Dict[str, Any], filepath: str) -> None:
    """Exports diagnostic results to CSV."""
    results = audit_data.get("results", [])
    with open(filepath, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "Proxy Endpoint",
            "Observed Exit IP",
            "HTTP Status",
            "Classification",
            "Latency (ms)",
            "Evidence / Details"
        ])
        for r in results:
            writer.writerow([
                r.get("endpoint"),
                r.get("exit_ip"),
                r.get("status_code"),
                r.get("category"),
                r.get("latency_ms"),
                r.get("evidence"),
            ])


def generate_html_report(audit_data: Dict[str, Any], filepath: str) -> None:
    """Renders HTML transparency report."""
    template = jinja2.Template(HTML_REPORT_TEMPLATE)
    html_out = template.render(
        timestamp=datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        legal_notice=LEGAL_PRIVACY_NOTICE,
        target_url=audit_data.get("target_url", "N/A"),
        target_intel=audit_data.get("target_intel"),
        total_requests=audit_data.get("total_requests", 0),
        direct_exposure_prevented=audit_data.get("direct_exposure_prevented", 0),
        results=audit_data.get("results", [])
    )
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(html_out)


def export_multi_format_reports(
    audit_data: Dict[str, Any],
    base_filepath: str
) -> Dict[str, str]:
    """Generates HTML, JSON, and CSV reports given a base filepath."""
    base_no_ext = os.path.splitext(base_filepath)[0]
    out_files = {}

    json_path = f"{base_no_ext}.json"
    generate_json_report(audit_data, json_path)
    out_files["json"] = json_path

    csv_path = f"{base_no_ext}.csv"
    generate_csv_report(audit_data, csv_path)
    out_files["csv"] = csv_path

    html_path = f"{base_no_ext}.html"
    generate_html_report(audit_data, html_path)
    out_files["html"] = html_path

    return out_files
